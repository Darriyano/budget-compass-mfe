import { TravelBotRequest, TravelBotResponse } from '../types'

export class TravelBotService {
  private static responses: Record<string, string> = {
    'где попробовать местную кухню':
      'Рекомендую посетить местные рынки и семейные рестораны. В Лиссабоне попробуйте паштел де ната, в Стамбуле - кебаб и баклаву.',
    транспорт:
      'В большинстве городов удобно пользоваться общественным транспортом. Рекомендую приобрести дневные или недельные проездные билеты.',
    достопримечательности:
      'Обязательно посетите исторический центр города, местные музеи и парки. Многие достопримечательности можно посмотреть бесплатно.',
    жилье:
      'Рекомендую бронировать жилье заранее. Хостелы - бюджетный вариант, апартаменты - для семей, отели - для комфорта.',
    безопасность:
      'Все рекомендуемые города безопасны для туристов. Следуйте общим правилам безопасности: не носите с собой крупные суммы, следите за вещами.',
  }

  static async askQuestion(
    request: TravelBotRequest,
  ): Promise<TravelBotResponse> {
    const question = request.question.toLowerCase().trim()

    // Ищем подходящий ответ
    for (const [key, answer] of Object.entries(this.responses)) {
      if (question.includes(key)) {
        return { answer }
      }
    }

    // Если не нашли точного совпадения, возвращаем общий ответ
    const generalAnswers = [
      'Это отличный вопрос! Рекомендую изучить местные блоги и форумы путешественников для получения актуальной информации.',
      'Для получения подробной информации советую обратиться к официальным туристическим сайтам города.',
      'Это зависит от ваших предпочтений и бюджета. Рекомендую составить план заранее.',
      'Интересный вопрос! Попробуйте поискать информацию в местных группах в социальных сетях.',
    ]

    const randomAnswer =
      generalAnswers[Math.floor(Math.random() * generalAnswers.length)]

    return { answer: randomAnswer }
  }
}
